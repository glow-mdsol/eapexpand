"""Generate docs/rules/core_enums.yaml from the cdisc-rules-engine rule schema docs.

Usage: python scripts/gen_core_enums.py /path/to/cdisc-rules-engine/resources/schema/rule
"""

import json
import re
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "rules" / "core_enums.yaml"
MAX_LEN = 220
CONST_RE = r'"operator": \{\s*"const": "([a-z_0-9]+)"'


def sections(path: Path) -> dict:
    """Map each ##/### heading to the first paragraph that follows it."""
    found, current, buf, fence = {}, None, [], False
    for line in path.read_text().splitlines():
        if line.startswith("```"):
            fence = not fence
        heading = None if fence else re.match(r"^#{2,3}\s+(.+?)\s*$", line)
        if heading:
            if current:
                found[current] = buf
            current, buf = heading.group(1), []
        elif current:
            buf.append(line)
    if current:
        found[current] = buf

    result = {}
    for name, lines in found.items():
        para = []
        for line in lines:
            stripped = line.strip()
            if stripped.startswith(("```", ">", "#")) or (
                stripped.startswith(("-", "*")) and para
            ):
                if para:
                    break
                continue
            if not stripped:
                if para:
                    break
                continue
            para.append(stripped)
        result[name] = re.sub(r"\s+", " ", " ".join(para)).replace("`", "").strip()
    return result


def short(text: str) -> str:
    if len(text) <= MAX_LEN:
        return text
    end = text.rfind(". ", 0, MAX_LEN)
    if end > 60:
        return text[: end + 1]
    return text[:MAX_LEN].rsplit(" ", 1)[0] + "..."


def enum(name: str, values: dict, description: str = "") -> str:
    lines = [f"  {name}:"]
    if description:
        lines.append(f"    description: {json.dumps(description)}")
    lines.append("    permissible_values:")
    for value, text in values.items():
        lines.append(f"      {value}:")
        if text:
            lines.append(f"        description: {json.dumps(short(text))}")
    return "\n".join(lines)


def main(rule_dir: Path) -> None:
    check_docs = sections(rule_dir / "Operator.md")
    op_docs = sections(rule_dir / "Operations.md")
    exec_docs = sections(rule_dir / "Executability.md")
    sens_docs = sections(rule_dir / "Sensitivity.md")

    def operators(json_name: str) -> list:
        text = json.dumps(json.load(open(rule_dir / json_name)), indent=1)
        return sorted(set(re.findall(CONST_RE, text)))

    rule_types = json.load(open(rule_dir / "Rule_Type.json"))["anyOf"]
    executability = json.load(open(rule_dir / "Executability.json"))["oneOf"]
    sensitivity = json.load(open(rule_dir / "Sensitivity.json"))["anyOf"]

    blocks = [
        enum(
            "RuleType",
            {c["const"]: c["title"] for c in rule_types},
            "Determines how the primary dataset is built before the rule is applied.",
        ),
        enum(
            "Executability",
            {c["const"]: exec_docs.get(c["const"], "") for c in executability},
            "Extent to which the rule can be executed automatically. "
            "Informational only; it does not control whether a rule runs.",
        ),
        enum(
            "Sensitivity",
            {c["const"]: sens_docs.get(c["const"], "") for c in sensitivity},
            "Granularity at which issues are reported.",
        ),
        enum(
            "CheckOperator",
            {o: check_docs.get(o, "") for o in operators("Operator.json")},
            "Operator used in a leaf condition of a Check.",
        ),
        enum(
            "OperationOperator",
            {o: op_docs.get(o, "") for o in operators("Operations.json")},
            "Operator used by an Operation to derive a value for use in a Check.",
        ),
    ]

    header = (
        "# Generated by scripts/gen_core_enums.py from the cdisc-rules-engine\n"
        "# rule schema docs. Do not edit by hand.\n"
        "id: https://cdisc.org/usdm/rules/core_enums\n"
        "name: USDM_Rules_CORE_Enums\n"
        "prefixes:\n"
        "  linkml: https://w3id.org/linkml/\n"
        "default_range: string\n"
        "enums:\n"
    )
    OUTPUT.write_text(header + "\n".join(blocks) + "\n")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
